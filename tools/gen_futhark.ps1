# Рисует атлас 24 рун Старшего Футарка (768x512, сетка 6x4 по 128) для рун в воздухе при касте pohsmp_core.
# Белые штрихи со свечением на чёрном (аддитивно, цвет даёт мод). Порядок: феху, уруз, турисаз, ансуз, райдо, кано, гебо, вуньо,
# хагалаз, наутиз, иса, йера, эйваз, перт, альгиз, соуло, тейваз, беркано, эваз, маназ, лагуз, ингуз, отал, дагаз.
# Использование: tools\gen_futhark.ps1 [файл_превью.png]
param([string]$Preview)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$root = Split-Path -Parent $PSScriptRoot
$out = Join-Path $root 'mods-src\pohsmp_core\src\main\resources\assets\pohsmp_core\textures\fx\futhark.png'

# каждая руна — список ломаных, точки в квадрате 0..1 (y вниз)
$R = @(
  @(@(.3,0,.3,1), @(.3,.35,.75,.05), @(.3,.62,.75,.32)),                         # феху
  @(@(.3,1,.3,.05,.75,.35,.75,1)),                                                # уруз
  @(@(.35,0,.35,1), @(.35,.28,.72,.5,.35,.72)),                                   # турисаз
  @(@(.3,0,.3,1), @(.3,.05,.72,.3), @(.3,.36,.72,.61)),                          # ансуз
  @(@(.3,0,.3,1), @(.3,.04,.72,.27,.3,.5,.74,1)),                                 # райдо
  @(@(.72,.12,.3,.5,.72,.88)),                                                    # кано
  @(@(.2,.05,.8,.95), @(.8,.05,.2,.95)),                                          # гебо
  @(@(.32,0,.32,1), @(.32,.04,.72,.27,.32,.5)),                                   # вуньо
  @(@(.25,0,.25,1), @(.75,0,.75,1), @(.25,.36,.75,.62)),                         # хагалаз
  @(@(.5,0,.5,1), @(.28,.34,.72,.62)),                                            # наутиз
  @(@(.5,0,.5,1)),                                                                # иса
  @(@(.48,.1,.22,.36,.48,.62), @(.52,.38,.78,.64,.52,.9)),                        # йера
  @(@(.5,0,.5,1), @(.5,.04,.78,.26), @(.5,.96,.22,.74)),                         # эйваз
  @(@(.3,0,.3,1), @(.3,.04,.62,.28,.82,.08), @(.3,.96,.62,.72,.82,.92)),          # перт
  @(@(.5,0,.5,1), @(.5,.42,.18,.06), @(.5,.42,.82,.06)),                         # альгиз
  @(@(.66,0,.3,.4,.7,.6,.34,1)),                                                  # соуло
  @(@(.5,0,.5,1), @(.5,0,.18,.32), @(.5,0,.82,.32)),                             # тейваз
  @(@(.3,0,.3,1), @(.3,0,.72,.25,.3,.5,.72,.75,.3,1)),                            # беркано
  @(@(.2,1,.2,0,.5,.36,.8,0,.8,1)),                                               # эваз
  @(@(.2,1,.2,0), @(.8,1,.8,0), @(.2,0,.8,.46), @(.8,0,.2,.46)),                 # маназ
  @(@(.36,1,.36,0,.76,.3)),                                                       # лагуз
  @(@(.5,.06,.82,.38,.5,.7,.18,.38,.5,.06), @(.18,.38,.06,.5), @(.82,.38,.94,.5)),# ингуз
  @(@(.18,1,.8,.36,.5,0,.2,.36,.82,1)),                                           # отал
  @(@(.2,0,.2,1), @(.8,0,.8,1), @(.2,0,.8,1), @(.8,0,.2,1))                      # дагаз
)
$cell = 128; $bmp = New-Object Drawing.Bitmap 768, 512, ([Drawing.Imaging.PixelFormat]::Format32bppArgb)
$g = [Drawing.Graphics]::FromImage($bmp); $g.SmoothingMode = 'AntiAlias'; $g.Clear([Drawing.Color]::Black)
function Pen([double]$w, [int]$a) { $p = New-Object Drawing.Pen ([Drawing.Color]::FromArgb(255, $a, $a, $a)), $w; $p.StartCap = 'Round'; $p.EndCap = 'Round'; $p.LineJoin = 'Round'; return $p }
for ($i = 0; $i -lt 24; $i++) {
  $ox = ($i % 6) * $cell; $oy = [Math]::Floor($i / 6) * $cell
  $pad = 26; $sz = $cell - 2 * $pad
  foreach ($layer in @(@(26, 28), @(18, 50), @(12, 90), @(7, 255))) {   # свечение снаружи внутрь, затем ядро
    $pen = Pen $layer[0] $layer[1]
    $lines = $R[$i]; if ($lines[0] -isnot [array]) { $lines = ,$lines }   # руна из одной ломаной PowerShell разворачивает
    foreach ($ln in $lines) {
      $pts = @(); for ($k = 0; $k -lt $ln.Count; $k += 2) { $pts += New-Object Drawing.PointF ([float]($ox + $pad + $ln[$k] * $sz)), ([float]($oy + $pad + $ln[$k + 1] * $sz)) }
      $g.DrawLines($pen, [Drawing.PointF[]]$pts)
    }
  }
}
$g.Dispose(); $bmp.Save($out, [Drawing.Imaging.ImageFormat]::Png)
if ($Preview) { $bmp.Save($Preview) }
$bmp.Dispose(); "futhark.png 768x512 (24 руны)"
