# ================================================================== математика поз
def R(p, y, r):
    return _rz(-r * D) @ _ry(-y * D) @ _rx(p * D)


def _rx(a):
    c, s = math.cos(a), math.sin(a)
    return np.array([[1, 0, 0], [0, c, -s], [0, s, c]])


def _ry(a):
    c, s = math.cos(a), math.sin(a)
    return np.array([[c, 0, s], [0, 1, 0], [-s, 0, c]])


def _rz(a):
    c, s = math.cos(a), math.sin(a)
    return np.array([[c, -s, 0], [s, c, 0], [0, 0, 1]])


def chest_frame(body, torso):
    """Позиция и поворот грудной клетки (сустав chestG превью) в осях модели, пиксели."""
    root = np.array([0.0, body.get('y', 0) * 16, body.get('z', 0) * 16])
    Rt = R(torso.get('pitch', 0), torso.get('yaw', 0), torso.get('roll', 0))
    tpos = root + [0, 12, 0]
    cpos = tpos + Rt @ [0, 6, 0]
    Rc = Rt @ _rx(torso.get('bend', 0) * D)
    return root, tpos, Rt, cpos, Rc


def fk(ch):
    """Прямая кинематика как в превью: ch — каналы позы {'body','torso','head','rightArm','leftArm','rightLeg','leftLeg'}.
    Возвращает точки (пиксели, оси модели) и направления."""
    body, torso = ch.get('body', {}), ch.get('torso', {})
    root, tpos, Rt, cpos, Rc = chest_frame(body, torso)
    out = {'root': root, 'pelvis': tpos, 'chest': cpos, 'Rc': Rc}
    hd = ch.get('head', {})
    Rh = Rc @ R(hd.get('pitch', 0), hd.get('yaw', 0), hd.get('roll', 0))
    out['head'] = cpos + Rc @ [0, 6, 0]
    out['head_fwd'] = Rh @ [0, 0, 1.0]
    out['chest_fwd'] = Rc @ [0, 0, 1.0]
    for side, sx in (('right', -1), ('left', 1)):
        a = ch.get(side + 'Arm', {})
        top = cpos + Rc @ [5 * sx, 4, 0]
        Ra = Rc @ R(a.get('pitch', 0), a.get('yaw', 0), a.get('roll', 0))
        elbow = top + Ra @ [sx * 1, -4, 0]
        Rl = Ra @ _rx(a.get('bend', 0) * D)
        out['sh_' + side[0]] = top
        out['elbow_' + side[0]] = elbow
        out['grip_' + side[0]] = elbow + Rl @ [0, -5, 0]
        out['hand_' + side[0]] = elbow + Rl @ [0, -6, 0]
        out['item_' + side[0]] = Rl @ [0, 0, 1.0]
        lg = ch.get(side + 'Leg', {})
        hip = root + [1.9 * sx, 12, 0]
        Rg = R(lg.get('pitch', 0), lg.get('yaw', 0), lg.get('roll', 0))
        knee = hip + Rg @ [0, -6, 0]
        foot = knee + Rg @ _rx(lg.get('bend', 0) * D) @ [0, -6, 0]
        out['hip_' + side[0]] = hip
        out['knee_' + side[0]] = knee
        out['foot_' + side[0]] = foot
        out['toe_' + side[0]] = Rg @ _rx(lg.get('bend', 0) * D) @ [0, 0, 1.0]
    return out


def solve_leg(side, root, foot, yaw, prev=None):
    """Нога: таз в root (+ бедро), подошва в точке foot (пиксели), носок повёрнут на yaw (PA, + вправо). Колено — вперёд (bend ≥ 0)."""
    sx = -1 if side == 'right' else 1
    hip = root + [1.9 * sx, 12, 0]
    x = np.array(prev if prev is not None else [0.0, 0.0, 5.0])   # pitch, roll, bend

    def f(v):
        Rg = R(v[0], yaw, v[1])
        return hip + Rg @ [0, -6, 0] + Rg @ _rx(v[2] * D) @ [0, -6, 0]
    tgt = np.asarray(foot, float)
    d = np.linalg.norm(tgt - hip)
    if d > 11.98:                                       # не дотянуться — вытянутая нога в сторону цели
        tgt = hip + (tgt - hip) * 11.98 / d
    for _ in range(30):
        e = f(x) - tgt
        if np.linalg.norm(e) < 1e-3:
            break
        J = np.zeros((3, 3))
        for k in range(3):
            dx = np.zeros(3)
            dx[k] = 0.05
            J[:, k] = (f(x + dx) - f(x - dx)) / 0.1
        step = np.linalg.lstsq(J, -e, rcond=None)[0]
        x = x + np.clip(step, -25, 25)
        x[2] = max(0.0, min(150.0, x[2]))
    return {'pitch': float(x[0]), 'yaw': float(yaw), 'roll': float(x[1]), 'bend': float(x[2])}, x


def look(Rc, yaw_w, pitch_w):
    """Голова смотрит в мир по (yaw +вправо, pitch +вниз) — углы относительно груди."""
    p, y, r = G._euler(Rc.T @ R(pitch_w, yaw_w, 0))
    return {'pitch': p, 'yaw': y, 'roll': r}


class Solver:
    """Поза из целей в мире -> каналы PlayerAnimator, с памятью (локти и колени не перескакивают)."""
    def __init__(self):
        self.u = {'right': None, 'left': None}
        self.leg = {'right': None, 'left': None}

    def arm(self, side, Rc, cpos, hand, item=None, fore=None, elbow_out=1.0, local=False):
        q = np.asarray(hand, float) if local else Rc.T @ (np.asarray(hand, float) - cpos) + [0, 18, 0]
        st = None if item is None else Rc.T @ G._n(item)
        fo = None if fore is None else (G._n(fore) if local else Rc.T @ G._n(fore))
        a, info = G.arm(side, q, st, elbow_out=elbow_out, fore=fo, prev_u=self.u[side])
        self.u[side] = info['u']
        return a

    def pose(self, s):
        body = {'y': s.get('by', 0.0), 'z': s.get('bz', 0.0)}
        torso = {'pitch': s.get('tp', 0.0), 'yaw': s.get('ty', 0.0), 'roll': s.get('tr', 0.0), 'bend': s.get('tb', 0.0)}
        root, tpos, Rt, cpos, Rc = chest_frame(body, torso)
        ch = {'body': body, 'torso': torso}
        ch['head'] = look(Rc, s.get('ly', 0.0), s.get('lp', 4.0))
        for side, k in (('right', 'r'), ('left', 'l')):
            if k + 'hl' in s:          # кисть в осях груди (как gen_player_anims: плечо в (∓5, 22, 0)), предмет — в мире, предплечье — в осях груди
                ch[side + 'Arm'] = self.arm(side, Rc, cpos, s[k + 'hl'], s.get(k + 'i'), s.get(k + 'f'), s.get(k + 'eo', 1.0), local=True)
            elif k + 'h' in s:
                ch[side + 'Arm'] = self.arm(side, Rc, cpos, s[k + 'h'], s.get(k + 'i'), s.get(k + 'f'), s.get(k + 'eo', 1.0))
            else:
                ch[side + 'Arm'] = dict(s.get(k + 'a', G.ARM_DOWN_R if side == 'right' else G.ARM_DOWN_L))
            ft = s.get(k + 'ft', ((-1.9 if side == 'right' else 1.9), 0.0, 0.0))
            fy = s.get(k + 'fy', 0.0)
            leg, self.leg[side] = solve_leg(side, root, [ft[0], 0.0 + s.get(k + 'fl', 0.0), ft[2]], fy, self.leg[side])
            ch[side + 'Leg'] = leg
        return ch


# ================================================================== кривые
EASE = {
    'l': lambda u: u,
    'io': lambda u: -(math.cos(math.pi * u) - 1) / 2,        # синус in-out: пик скорости посередине
    'o': lambda u: 1 - (1 - u) ** 3,                         # out cubic: замедление в позу
    'oq': lambda u: 1 - (1 - u) ** 2,
    'i': lambda u: u ** 3,
    'iq': lambda u: u * u,
    'ob': lambda u: 1 + 2.2 * (u - 1) ** 3 + 1.2 * (u - 1) ** 2,  # лёгкий перелёт (back)
}


def K(t, keys):
    """keys: [(тик, значение, плавность к этому ключу)], значение — число или вектор. До первого — первое, после последнего — последнее."""
    if t <= keys[0][0]:
        return np.asarray(keys[0][1], float) if not np.isscalar(keys[0][1]) else float(keys[0][1])
    for (t0, v0, _), (t1, v1, e) in zip(keys, keys[1:]):
        if t <= t1:
            u = EASE[e]((t - t0) / max(1e-9, t1 - t0))
            if np.isscalar(v0):
                return v0 + (v1 - v0) * u
            return np.asarray(v0, float) + (np.asarray(v1, float) - np.asarray(v0, float)) * u
    v = keys[-1][1]
    return float(v) if np.isscalar(v) else np.asarray(v, float)


def dirv(yaw, pitch=0.0):
    """Направление в осях модели: yaw + — ВПРАВО (к −X), pitch + — вниз."""
    return np.array([-math.sin(yaw * D) * math.cos(pitch * D), -math.sin(pitch * D), math.cos(yaw * D) * math.cos(pitch * D)])


