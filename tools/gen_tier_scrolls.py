def make(sid, tier, acc, em):
    T = TIERS[tier]
    ink = {k: h(v) for k, v in T['ink'].items()}
    ink['4'], ink['5'] = h(acc[0]), h(acc[1])
    im = Image.new('RGBA', (32, 32), (0, 0, 0, 0))
    for y0 in (3, 23):
        for dy, row in enumerate(ROD):
            for dx, c in enumerate(row):
                im.putpixel((3 + dx, y0 + dy), h(T['rod'][c]))
    for i, (l, r) in enumerate(PAPER):
        y = 9 + i
        for x in range(l, r + 1):
            c = T['edge'] if x in (l, r) else T['sh1'] if x == l + 1 else T['sh2'] if x == l + 2 else T['light'] if (x + y * 3) % 11 == 0 else T['base']
            im.putpixel((x, y), h(c))
    for dy, row in enumerate(em):
        for dx, c in enumerate(row):
            p = (8 + dx, 11 + dy)
            if c != '.' and im.getpixel(p)[3]:
                im.putpixel(p, ink[c])
    # светлые штрихи на светлой бумаге не видны: обводим их тёмным цветом ступени (только по бумаге вокруг)
    pts = {(8 + dx, 11 + dy) for dy, row in enumerate(em) for dx, c in enumerate(row) if c != '.'}
    lum = lambda c: 0.3 * c[0] + 0.59 * c[1] + 0.11 * c[2]
    for (x, y) in list(pts):
        if lum(im.getpixel((x, y))) < 175:
            continue
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if (nx, ny) not in pts and 0 <= nx < 32 and im.getpixel((nx, ny))[3] and 10 <= ny <= 21 and nx not in [l for l, r in PAPER] :
                im.putpixel((nx, ny), ink['2'])
    for x in range(9, 23, 3):
        if im.getpixel((x, 21))[3]:
            im.putpixel((x, 21), ink['1']); im.putpixel((x + 1, 21), ink['2'])
    im.save(os.path.join(A, 'textures', 'item', f'scroll_{sid}.png'))
    with open(os.path.join(A, 'models', 'item', f'scroll_{sid}.json'), 'w', encoding='utf-8') as f:
        json.dump({'parent': 'item/generated', 'textures': {'layer0': f'pohsmp_core:item/scroll_{sid}'}}, f, indent=2)
        f.write('\n')
    return im


if __name__ == '__main__':
    for sid, (tier, acc, em) in E.items():
        assert len(em) == 10 and all(len(r) == 16 for r in em), sid
        make(sid, tier, acc, em)
        print('wrote scroll_%s (%s)' % (sid, tier))
