#!/usr/bin/env python3
"""
T32 п. 4 «Сломать блок» — Эреб (ereb_guard_break): ложный финт рапирой в лицо, перевод клинка вниз и длинный выпад под защиту.
Позы — целями в мире, углы — решателями tools/guard_break_lib.py (FK как у проверки: знаки не переворачиваются).
Вызывается из tools/gen_ereb_anims.build(); ткань (полы камзола) потом дописывает anim_cloth.bake, как у всех ereb_*.

Тайминг: warn 0.10 (тик 2; вспышка на острие), hit 0.70 (тик 14), длина 1.8 с (36 тиков).
  0.10–0.32 финт: аппель (правая стопа притоп вперёд), рука выбрасывает остриё к лицу цели — цель поднимает защиту;
  0.32–0.50 перевод: остриё по дуге уходит вниз под защиту, корпус скручивается влево, вес назад, колени согнуты;
  0.50–0.60 взвод (медленное дотягивание); 0.60–0.74 выпад: шаг правой, таз вперёд-вниз, плечи доворачивают, укол под защиту
  (пик скорости острия ~0.69); 0.74–0.88 держит руку (у укола эталон держит вытянутую руку 0.06–0.16 с);
  0.88–1.8 возврат: отшаг правой, рука в стойку «ан гард».
"""
import numpy as np

import guard_break_lib as GL
from guard_break_lib import Keys, yaw_dir

WARN, HIT, LENGTH = 0.10, 0.70, 1.8
TARGET = np.array([0.0, 0.0, -40.0])          # цель (игрок в блоке) — 2.5 бл. впереди

# стойка «ан гард» (как ereb_guard): правый бок к цели
G0 = dict(body=(4.0, -38.0, 0.0), torso=(0.0, 4.0, 0.0), pel=(0.0, 0.0), drop=1.2,
          rf=(1.7, -5.7, -10.0, 0.0), lf=(-1.2, 5.9, -22.0, 0.0), larm=(-150.0, -10.0, -40.0))


def special(M):
    return {'strike': (np.zeros(3), M.axis_far)}


def build():
    M = GL.JModel('ereb', anims={})
    sv = GL.Solver(M)

    K = Keys([
        (0.0, dict(G0)),
        (0.10, dict(body=(4.0, -39.0, 0.0)), 'io'),
        (0.22, dict(body=(9.0, -42.0, 1.0), pel=(0.0, -1.2), rf=(1.8, -7.2, -8.0, 1.6), drop=1.0), 'out'),
        (0.30, dict(body=(10.0, -40.0, 0.0), pel=(0.0, -1.8), rf=(1.8, -8.4, -8.0, 0.0), drop=1.3), 'in'),
        (0.48, dict(body=(2.0, -72.0, -3.0), torso=(-2.0, -6.0, 0.0), pel=(0.4, 1.2), drop=2.2,
                    larm=(-164.0, -10.0, -26.0)), 'out'),
        (0.60, dict(body=(1.0, -77.0, -3.0), torso=(-3.0, -7.0, 0.0), pel=(0.5, 1.5), drop=2.4, rf=(1.8, -8.4, -8.0, 0.8)), 'lin'),
        (0.66, dict(body=(10.0, -52.0, 0.0), torso=(2.0, 0.0, 0.0), pel=(0.2, -3.0), drop=2.6), 'in'),
        (0.71, dict(body=(20.0, -18.0, 3.0), torso=(6.0, 8.0, 0.0), pel=(0.0, -6.0), drop=3.0, rf=(2.2, -14.5, -4.0, 0.0),
                    lf=(-1.6, 5.0, -30.0, 0.0), larm=(34.0, -8.0, -34.0)), 'in'),
        (0.78, dict(body=(22.0, -14.0, 3.0), torso=(7.0, 10.0, 0.0), pel=(0.0, -6.4), drop=3.2), 'out2'),
        (0.82, dict(body=(20.0, -18.0, 2.0), torso=(5.0, 7.0, 0.0), pel=(0.0, -6.0), drop=3.0, rf=(2.2, -14.5, -4.0, 0.0),
                    lf=(-1.6, 5.0, -30.0, 0.0), larm=(30.0, -8.0, -36.0)), 'io'),
        (1.12, dict(body=(10.0, -34.0, 1.0), torso=(2.0, 4.0, 0.0), pel=(0.0, -3.0), drop=2.0, rf=(2.0, -10.0, -8.0, 1.6)), 'io'),
        (1.32, dict(rf=(1.7, -5.7, -10.0, 0.0), pel=(0.0, -0.6), drop=1.6, larm=(-140.0, -10.0, -44.0)), 'io'),
        (1.80, dict(G0), 'io'),
    ])
    # оружие: кисть (R-мир, точка) и направление клинка (yaw — вправо +, pitch — вверх +), путь по s, профиль s(t)
    ST = GL.stime([(0, 0.0), (0.10, 0.0, 'lin'), (0.30, 0.22, 'out'), (0.48, 0.40, 'io'), (0.62, 0.44, 'lin'),
                   (0.735, 0.80, ('beta', 2.1, 2.0)), (0.82, 0.82, 'out'), (1.80, 1.0, 'io')])
    P = [(0.0, dict(hx=4.4, hy=17.8, hz=-12.2, byaw=-5.0, bpit=6.0)),
         (0.22, dict(hx=4.2, hy=21.5, hz=-18.0, byaw=-3.0, bpit=12.0)),        # финт: остриё к лицу цели
         (0.30, dict(hx=4.6, hy=19.0, hz=-15.0, byaw=8.0, bpit=0.0)),          # остриё уходит вправо-вниз (перевод)
         (0.40, dict(hx=7.0, hy=14.2, hz=-1.5, byaw=5.0, bpit=-12.0)),         # под защиту, кисть к бедру
         (0.44, dict(hx=7.2, hy=14.0, hz=-0.5, byaw=5.0, bpit=-12.0)),
         (0.80, dict(hx=3.0, hy=11.5, hz=-21.0, byaw=-2.0, bpit=-6.0)),        # укол: рука вытянута, остриё в живот цели
         (0.82, dict(hx=3.0, hy=11.8, hz=-20.6, byaw=-2.0, bpit=-5.0)),
         (1.0, dict(hx=4.4, hy=17.8, hz=-12.2, byaw=-5.0, bpit=6.0))]

    def pose(t):
        o = {'body': {'rotation': K.v(t, 'body'), 'position': [0.0, 0.0, 0.0]}}
        pel = K.v(t, 'pel')
        o['body']['position'] = [pel[0], 0.0, pel[1]]
        o['torso'] = {'rotation': K.v(t, 'torso')}
        feet = {'right_leg': tuple(K.v(t, 'rf')), 'left_leg': tuple(K.v(t, 'lf'))}
        sv.legs(o, feet, drop=K.f(t, 'drop'))
        by, bp = K.v(t, 'body')[1], K.v(t, 'body')[0]
        tl = max(0.0, t - 0.06)                           # голова догоняет плечи с запаздыванием ~60 мс, смотрит на цель
        by_l = K.v(tl, 'body')[1]
        o['head'] = {'rotation': [-0.75 * bp + 2.0, -0.92 * by_l + 0.3 * (by_l - by), 0.0]}
        o['left_arm'] = {'rotation': K.v(t, 'larm')}
        o['bipedHandLeft'] = {'rotation': [0.0, 0.0, 0.0]}
        w = GL.path_at(P, ST(t))
        hand = np.array([w['hx'], w['hy'], w['hz']]) + np.array([pel[0], 0.0, pel[1]]) * 0.0
        sv.arm(o, 'right', hand)
        sv.wrist(o, yaw_dir(w['byaw'], w['bpit']))
        o['right_leg'] = {'rotation': o['right_leg']['rotation']}
        return o

    sv.reset()
    for _ in range(2):                                 # прогон «вхолостую» — решения стартуют с ветви 0-го кадра
        pose(0.0)
    # края — сшивка со стойкой ereb_guard (её ключи кисти — уже под двойной поворот GeckoLib): вход и выход без скачка крена клинка
    p0 = GL.pose_at('ereb', 'ereb_guard', 0.0, ('body', 'torso', 'head', 'right_arm', 'left_arm', 'right_leg', 'left_leg', 'bipedHandRight', 'bipedHandLeft'))
    return GL.bake(GL.blend_edges(pose, p0, LENGTH), LENGTH, 0.02, events={WARN: 'warn', HIT: 'hit'})
