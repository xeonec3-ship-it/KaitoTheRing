#!/usr/bin/env python3
"""
T32 п. 4 «Сломать блок» — Мартин (martin_guard_break): удар НАВЕРШИЕМ в блок, затем толчок ЩИТОМ.
Каркас и правила — пилот T29 (tools/gen_martin_ef.py, docs/specs/anim_style_epicfight.md): тело ключевыми позами (anim_body.Keys),
стопы на земле, оружие — путь по параметру s и профиль скорости s(t). Всё во внутренних осях (o['_int'] = True).

Тайминг (общий для всех боссов T32, см. docs/inbox/2026-11-21_mgr_guard_break_visuals.md): warn 0.10 с (тик 2, вспышка на навершии,
12 тиков до удара), hit 0.70 с (тик 14) — навершие в блок; щит — 1.0 с (продолжение, урона нет); длина 2.0 с (40 тиков).
Фазы: замах 0.10–0.50 (меч переворачивается навершием вперёд к правому плечу, плечи −85°, вес назад), взвод до 0.60 (левая
нога поднимается), удар 0.60–0.76 (шаг левой, таз вперёд-вниз, плечи −86° → +14°, пик скорости навершия ~0.69), перехлёст,
затем контр-поворот плеч −38° — щит с левого плеча вперёд (1.0), отдача, возврат с шагом назад до 2.0.
Вызывается из gen_martin.anims() после gen_martin_ef.define().
"""
import gen_martin_ef as EF
from anim_body import Keys
from gen_martin_ef import GUARD_W, STime, path_at

WARN, HIT, LENGTH = 0.10, 0.70, 2.0


def define(A, m, G, g, sf):
    bd = EF.Body(m, G, g, sf)
    vis = G.vis

    T = STime([(0, 0), (0.10, 0.0, 'lin'), (0.50, 0.22, 'out'), (0.60, 0.25, 'lin'), (0.76, 0.78, ('beta', 2.2, 2.0)),
               (0.86, 0.83, 'out'), (1.05, 0.90, 'io'), (2.00, 1.0, 'io')])
    P = [(0.0, dict(GUARD_W)),
         (0.10, dict(hphi=-62.0, hr=8.0, hy=21.0, byaw=-20.0, bth=86.0)),        # клинок встаёт вертикально справа
         (0.22, dict(hphi=-98.0, hr=6.4, hy=24.0, byaw=24.0, bth=118.0)),        # кисть у правого плеча, клинок вверх-назад-вправо
         (0.25, dict(hphi=-102.0, hr=6.4, hy=24.4, byaw=27.0, bth=121.0)),
         (0.45, dict(hphi=-58.0, hr=11.0, hy=22.6, byaw=32.0, bth=136.0)),
         (0.78, dict(hphi=-4.0, hr=16.6, hy=20.6, byaw=36.0, bth=152.0)),        # навершие в блок (клинок назад над правым плечом)
         (0.83, dict(hphi=5.0, hr=15.8, hy=19.6, byaw=38.0, bth=157.0)),
         (0.8301, dict(hphi=5.0, hr=15.8, hy=19.6, byaw=-142.0, bth=23.0)),     # то же направление (θ>90 ↔ yaw−180): дальше без проворота
         (0.90, dict(hphi=-104.0, hr=8.4, hy=13.4, byaw=-72.0, bth=40.0)),       # меч уходит вправо, клинок вверх-вправо мимо рогов — место щиту
         (1.0, dict(GUARD_W))]
    K = Keys([
        (0.0, dict(yaw=-32.0, pitch=-4.0, roll=0.0, tyaw=0.0, tpitch=0.0, pel=(0.3, 0.0), drop=0.35, hpitch=0.0,
                   rf=(3.4, 2.5, -38.0, 0.0), lf=(-2.6, -2.7, -8.0, 0.0))),
        (0.10, dict(yaw=-36.0, pitch=-3.0), 'io'),
        (0.50, dict(yaw=-84.0, pitch=6.0, roll=-6.0, tyaw=6.0, pel=(0.7, 1.7), drop=0.65, hpitch=4.0,
                    rf=(3.4, 2.5, -55.0, 0.0), lf=(-2.4, -1.8, -18.0, 0.0)), 'out'),
        (0.60, dict(yaw=-88.0, pitch=7.0, roll=-7.0, tyaw=7.0, pel=(0.7, 1.9), drop=0.75, lf=(-2.5, -2.4, -14.0, 1.3)), 'lin'),
        (0.66, dict(yaw=-44.0, tyaw=-4.0, rf=(3.4, 2.5, -25.0, 0.0)), 'in'),
        (0.71, dict(yaw=8.0, pitch=-15.0, roll=4.0, tyaw=-9.0, pel=(-0.5, -5.4), drop=1.5, hpitch=-6.0,
                    rf=(3.3, 1.0, -8.0, 0.0), lf=(-3.4, -9.6, 6.0, 0.0)), 'in'),
        (0.79, dict(yaw=15.0, pitch=-17.0, roll=5.0, tyaw=-6.0, pel=(-0.6, -6.0), drop=1.6), 'out2'),
        (0.88, dict(yaw=-6.0, pitch=-15.0, roll=0.0, tyaw=2.0), 'io'),
        (1.00, dict(yaw=-40.0, pitch=-21.0, roll=-3.0, tyaw=6.0, pel=(-0.5, -7.0), drop=1.7, hpitch=-8.0,
                    rf=(3.2, 0.2, -20.0, 0.0)), 'in'),
        (1.12, dict(yaw=-32.0, pitch=-15.0, tyaw=0.0, pel=(-0.4, -6.4), drop=1.4), 'back'),
        (1.35, dict(yaw=-30.0, pitch=-12.0, pel=(-0.3, -5.8), drop=1.3, lf=(-3.4, -9.6, 6.0, 0.0), rf=(3.2, 0.2, -20.0, 0.0)), 'io'),
        (1.55, dict(lf=(-3.0, -6.0, -2.0, 1.1), pel=(-0.1, -3.4), drop=0.9, hpitch=-2.0), 'io'),
        (1.75, dict(lf=(-2.6, -2.7, -8.0, 0.0), rf=(3.4, 2.5, -36.0, 0.0), pel=(0.2, -1.0), drop=0.5), 'io'),
        (2.00, dict(yaw=-32.0, pitch=-4.0, roll=0.0, tyaw=0.0, pel=(0.3, 0.0), drop=0.35, hpitch=0.0, rf=(3.4, 2.5, -38.0, 0.0)), 'io'),
    ])
    # щит в левой руке: k — поднят (0 — на спине), side — у левого бока (во время удара навершием), p — толчок вперёд
    SH = Keys([(0, dict(k=0.0, side=1.0, p=0.0)), (0.08, dict(k=0.0)), (0.40, dict(k=1.0), 'out'), (0.80, dict(side=1.0, p=0.0)),
               (0.92, dict(side=0.0, p=0.25), 'io'), (1.00, dict(p=1.0), 'in'), (1.12, dict(p=0.55), 'back'),
               (1.50, dict(k=1.0, side=0.0, p=0.2), 'io'), (1.85, dict(k=0.0, side=0.6, p=0.0), 'io')])

    def frame(t):
        o = bd.body(K, t)
        k, side, p = SH.f(t, 'k'), SH.f(t, 'side'), SH.f(t, 'p')
        if k > 0.01:
            hx, hz = -1.2 - 4.6 * side, -6.0 + 2.4 * side - 4.8 * p
            sf(o, (hx, 15.6 + 0.4 * p, hz), tilt=-4 - 8 * p, yaw=-12 + 6 * p + 34 * side, w=min(1.0, k * 1.3))
        bd.weapon(o, path_at(P, T(t)), left=0.0)
        return vis(o, shield_hand=0.08 < t < 1.85)

    a = A('guard_break', LENGTH)
    a.sample(frame, 0.02)
    a.instruction(WARN, 'warn')
    a.instruction(HIT, 'hit')
    return a
